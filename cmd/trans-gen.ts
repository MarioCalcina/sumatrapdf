interface Lang {
  desc: string[];
  code: string;
  name: string;
  isRtl: boolean;
}

// escape as octal number for C, as \nnn
function cOct(c: number): string {
  console.assert(c >= 0x80);
  let s = c.toString(8); // base 8 for octal
  while (s.length < 3) {
    s = "0" + s;
  }
  return `\\${s}`;
}

function cEscape(txt: string): string {
  // escape all quotes
  txt = txt.replaceAll(`"`, `\\"`);
  // and all non-7-bit characters of the UTF-8 encoded string
  const encoder = new TextEncoder();
  const bytes = encoder.encode(txt);
  let res = "";
  for (const c of bytes) {
    if (c < 0x80) {
      res += String.fromCharCode(c);
    } else {
      res += cOct(c);
    }
  }
  return `"${res}"`;
}

function newLang(desc: string[]): Lang {
  console.assert(desc.length <= 3);
  const lang: Lang = {
    desc,
    code: desc[0],
    name: desc[1],
    isRtl: false,
  };
  if (desc.length > 2) {
    console.assert(desc[2] === "RTL");
    lang.isRtl = true;
  }
  return lang;
}

const compactCTmpl = `// Generated by bun cmd/trans-gen.ts.

#include "base/Base.h"
#include "Translations.h"

namespace trans {

struct LangInfo {
    Str code;
    Str name;
    bool isRtl;
};

// clang-format off
static const LangInfo langs[] = {
{{langs}}
};
// clang-format on

int GetLangsCount() {
    return dimofi(langs);
}

int FindLangIdx(Str code) {
    for (int i = 0; i < GetLangsCount(); i++) {
        if (len(langs[i].code) == len(code) && MemEq(langs[i].code.s, code.s, len(code))) {
            return i;
        }
    }
    return -1;
}

static const LangInfo* GetLang(int idx) {
    ReportIf(idx < 0);
    idx = std::max(idx, 0);
    return idx < GetLangsCount() ? &langs[idx] : nullptr;
}

TempStr GetLangCodeByIdxTemp(int idx) {
    const LangInfo* lang = GetLang(idx);
    return lang ? lang->code : Str{};
}

TempStr GetLangNameByIdxTemp(int idx) {
    const LangInfo* lang = GetLang(idx);
    return lang ? lang->name : Str{};
}

bool IsLangRtl(int idx) {
    return idx >= 0 && idx < GetLangsCount() && langs[idx].isRtl;
}

} // namespace trans
`;

function genTranslationInfoCpp() {
  // sort: "en" first, then alphabetically by name
  gLangs.sort((x, y) => {
    if (x[0] === "en") return -1;
    if (y[0] === "en") return 1;
    return x[1] < y[1] ? -1 : x[1] > y[1] ? 1 : 0;
  });

  const langs = gLangs.map((desc) => newLang(desc));
  console.assert(langs[0].code === "en");

  const rows = langs.map((lang) => `    {StrL(${cEscape(lang.code)}), StrL(${cEscape(lang.name)}), ${lang.isRtl}},`);
  const fileContent = compactCTmpl.replace("{{langs}}", rows.join("\n"));

  const path = join("src", "ng", "TranslationLangs.cpp");
  console.log(`fileContent: path: ${path}, file size: ${fileContent.length}`);
  Bun.write(path, fileContent);
}

genTranslationInfoCpp();
