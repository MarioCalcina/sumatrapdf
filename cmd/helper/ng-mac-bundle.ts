// Wraps the mac executable in SumatraPDF.app so Finder can offer it in
// "Open With" and make it the default viewer.
//
//   SumatraPDF.app/Contents/Info.plist
//                          /MacOS/SumatraPDF
//                          /Resources/SumatraPDF.icns
//                          /Resources/<lang>.lproj/InfoPlist.strings

import { constants, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { macMinVersion } from "./ng-toolchain";

const bundleId = "org.sumatrapdfreader.SumatraPDF";
// generated by cmd/update-mac-icon.ts from src/gfx/mac/icon.png
const iconSrc = "src/gfx/mac/SumatraPDF.icns";
const iconName = "SumatraPDF.icns";
// texts macOS shows for the app, such as why it asks for the local network
const plistTextsSrc = "translations/infoplist.txt";

type DocType = { name: string; utis?: string[]; exts?: string[] };

// a type without a system UTI is matched by extension
const docTypes: DocType[] = [
  { name: "PDF Document", utis: ["com.adobe.pdf"] },
  { name: "EPUB Document", utis: ["org.idpf.epub-container"] },
  { name: "Image", utis: ["public.png", "public.jpeg", "public.tiff", "com.compuserve.gif", "com.microsoft.bmp"] },
  { name: "Comic Book", exts: ["cbz", "cbr", "cb7", "cbt"] },
  { name: "DjVu Document", exts: ["djvu", "djv"] },
  { name: "XPS Document", exts: ["xps", "oxps"] },
  { name: "Ebook", exts: ["mobi", "azw", "azw3", "fb2", "fb2z", "pdb", "prc"] },
  { name: "CHM Document", exts: ["chm"] },
  { name: "PostScript Document", exts: ["ps", "eps"] },
  { name: "WebP Image", exts: ["webp"] },
  { name: "AVIF Image", exts: ["avif"] },
  { name: "HEIF Image", exts: ["heic", "heif"] },
  { name: "JPEG XL Image", exts: ["jxl"] },
];

// the languages of src/shared/TranslationLangs.cpp as Apple language ids. Listed
// in CFBundleLocalizations, they let AppKit's own UI (print and open panels, the
// menu items it adds) follow the app's language instead of staying English.
// es-419 gives Latin America its own AppKit Spanish.
const appleLangs = (
  "en af ar az be bg bn bs ca co cs cy da de el es es-419 et eu fa fi fil fo fr fy ga gl he hi hr hu hy id it " +
  "ja jv ka ko ku kw lt lv mk ml ms my nb ne nl nn pa pl pt-BR pt-PT ro ru sat si sk sl sn sq sr sr-Latn sv ta " +
  "th tr uk uz vi zh-Hans zh-Hant"
).split(" ");

// Apple language ids our table (translations.txt) spells differently
const ourLangCodes: Record<string, string> = {
  be: "by",
  cs: "cz",
  da: "dk",
  "es-419": "es",
  fil: "tl",
  fy: "fy-nl",
  hy: "am",
  ko: "kr",
  ms: "my",
  my: "mm",
  nb: "no",
  "pt-BR": "br",
  "pt-PT": "pt",
  sr: "sr-rs",
  "sr-Latn": "sp-rs",
  vi: "vn",
  "zh-Hans": "cn",
  "zh-Hant": "tw",
};

type PlistTexts = Map<string, Map<string, string>>; // key -> our lang -> text

// ":Key" lines, then "lang:text" lines
function readPlistTexts(root: string): PlistTexts {
  const texts: PlistTexts = new Map();
  let cur: Map<string, string> | undefined;
  for (const line of readFileSync(join(root, plistTextsSrc), "utf8").replace(/\r/g, "").split("\n")) {
    if (!line || line.startsWith("#")) continue;
    if (line.startsWith(":")) {
      cur = new Map();
      texts.set(line.slice(1), cur);
      continue;
    }
    const i = line.indexOf(":");
    if (!cur || i < 0) throw new Error(`${plistTextsSrc}: bad line '${line}'`);
    cur.set(line.slice(0, i), line.slice(i + 1));
  }
  return texts;
}

function stringsLiteral(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function writePlistTexts(resDir: string, texts: PlistTexts): void {
  for (const lang of appleLangs) {
    const ours = ourLangCodes[lang] ?? lang;
    const lines: string[] = [];
    for (const [key, byLang] of texts) {
      const text = byLang.get(ours);
      if (!text) throw new Error(`${plistTextsSrc}: no '${ours}' text for ${key}`);
      lines.push(`${stringsLiteral(key)} = ${stringsLiteral(text)};`);
    }
    const dir = join(resDir, `${lang}.lproj`);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "InfoPlist.strings"), lines.join("\n") + "\n");
  }
}

function plistArray(items: string[]): string {
  return `<array>${items.map((s) => `<string>${s}</string>`).join("")}</array>`;
}

function docTypePlist(t: DocType): string {
  const match = t.utis
    ? `<key>LSItemContentTypes</key>${plistArray(t.utis)}`
    : `<key>CFBundleTypeExtensions</key>${plistArray(t.exts!)}`;
  return `    <dict>
      <key>CFBundleTypeName</key><string>${t.name}</string>
      <key>CFBundleTypeRole</key><string>Viewer</string>
      <key>LSHandlerRank</key><string>Alternate</string>
      ${match}
    </dict>`;
}

function infoPlist(exeName: string, version: string, texts: PlistTexts): string {
  const textKeys = [...texts].map(([key, byLang]) => `  <key>${key}</key><string>${byLang.get("en")}</string>`);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>SumatraPDF</string>
  <key>CFBundleDisplayName</key><string>SumatraPDF</string>
  <key>CFBundleIdentifier</key><string>${bundleId}</string>
  <key>CFBundleExecutable</key><string>${exeName}</string>
  <key>CFBundleIconFile</key><string>${iconName}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>CFBundleVersion</key><string>${version}</string>
  <key>NSPrincipalClass</key><string>NSApplication</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSMinimumSystemVersion</key><string>${macMinVersion}</string>
  <key>CFBundleDevelopmentRegion</key><string>en</string>
  <key>CFBundleLocalizations</key>${plistArray(appleLangs)}
${textKeys.join("\n")}
  <key>CFBundleDocumentTypes</key>
  <array>
${docTypes.map(docTypePlist).join("\n")}
  </array>
</dict>
</plist>
`;
}

function run(cmd: string[]): void {
  const p = Bun.spawnSync(cmd, { stdout: "pipe", stderr: "pipe" });
  if (p.exitCode !== 0) throw new Error(`${cmd.join(" ")} failed:\n${p.stderr.toString()}`);
}

function isNewer(a: string, b: string): boolean {
  return existsSync(b) && statSync(b).mtimeMs >= statSync(a).mtimeMs;
}

export function makeMacBundle(root: string, exe: string, version: string): string {
  const exeName = basename(exe);
  const outDir = join(exe, "..");
  const app = join(outDir, `${exeName}.app`);
  const macOsDir = join(app, "Contents", "MacOS");
  const resDir = join(app, "Contents", "Resources");
  mkdirSync(macOsDir, { recursive: true });
  mkdirSync(resDir, { recursive: true });

  const bundleExe = join(macOsDir, exeName);
  if (!isNewer(exe, bundleExe)) {
    rmSync(bundleExe, { force: true });
    // a clone on APFS: no second copy of the binary on disk
    copyFileSync(exe, bundleExe, constants.COPYFILE_FICLONE);
  }
  copyFileSync(join(root, iconSrc), join(resDir, iconName));
  const texts = readPlistTexts(root);
  writePlistTexts(resDir, texts);
  writeFileSync(join(app, "Contents", "Info.plist"), infoPlist(exeName, version, texts));
  // seals Info.plist, the icon and the texts into the signature
  run(["codesign", "--force", "--sign", "-", app]);
  return app;
}
